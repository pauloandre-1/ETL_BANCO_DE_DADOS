CREATE DATABESE VENDAS;

CREATE TABLE VENDA (
	IDVENDA INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
	NOME_PRODUTO VARCHAR(30) NOT NULL,
	VALOR_UNITARIO DECIMAL(10,2) UNSIGNED NOT NULL,
	QUANTIDADE INT UNSIGNED NOT NULL, 
	DATA_VENDA DATETIME DEFAULT CURRENT_TIMESTAMP
	
);

CREATE TABLE LUCRO (
	IDLUCRO INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
	ID_VENDA INT UNSIGNED NOT NULL UNIQUE COMMENT "CHAVE ESTRANGEIRA",
	FATURAMENTO DECIMAL(10,2)UNSIGNED COMMENT "CAMPO CALCULADO",
	DATA_ATUALIZACAO DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
	FOREIGN KEY (ID_VENDA) REFERENCES VENDA(IDVENDA)


);

